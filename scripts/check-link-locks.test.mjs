import assert from "node:assert/strict";
import { copyFileSync, mkdirSync, mkdtempSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import test from "node:test";
import { LOCKFILES, checkLinkLocks, linkedCrates } from "./check-link-locks.mjs";

const scriptUrl = new URL("./check-link-locks.mjs", import.meta.url);
const script = fileURLToPath(scriptUrl);
const IROH = ["iroh 1.4.1", "iroh-base 1.4.1", "iroh-relay 1.4.1", "noq 1.4.0", "noq-proto 1.4.0"];

/** A Cargo.lock naming each "name version", laid out as cargo writes one. */
function cargoLock(crates, eol = "\n") {
  const tables = crates.map((crate) => {
    const [name, version] = crate.split(" ");
    return [
      "[[package]]",
      `name = "${name}"`,
      `version = "${version}"`,
      'source = "registry+https://github.com/rust-lang/crates.io-index"',
      "dependencies = [",
      ' "iroh 1.3.0",',
      ' "noq",',
      "]",
    ].join(eol);
  });
  const head = ["# This file is automatically @generated by Cargo.", "version = 4", ""];
  return [...head, tables.join(eol + eol), ""].join(eol);
}

/** A checkout with the two lockfiles, and the script in its scripts/. */
function checkout(t, app, link) {
  const root = realpathSync.native(mkdtempSync(join(tmpdir(), "kleio-link-locks-")));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  for (const [path, text] of [
    [LOCKFILES[0], app],
    [LOCKFILES[1], link],
  ]) {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), text);
  }
  mkdirSync(join(root, "scripts"));
  copyFileSync(script, join(root, "scripts", "check-link-locks.mjs"));
  return root;
}

function run(root) {
  return spawnSync(process.execPath, [join(root, "scripts", "check-link-locks.mjs")], {
    encoding: "utf8",
  });
}

test("import has no CLI effects", () => {
  const result = spawnSync(
    process.execPath,
    ["--input-type=module", "-e", `await import(${JSON.stringify(scriptUrl.href)})`],
    { encoding: "utf8" },
  );
  assert.equal(result.status, 0, result.stderr);
  assert.equal(result.stdout, "");
  assert.equal(result.stderr, "");
});

test("reads the iroh and noq crates a lockfile names, and nothing else", () => {
  const lock = cargoLock([
    "tokio 1.53.1",
    "noq 1.4.0",
    "iroh 1.4.1",
    "irohx 2.0.0",
    "noqa 1.0.0",
    "my-iroh 1.0.0",
    "iroh-base 1.4.1",
    "noq 1.3.0",
  ]);
  assert.deepEqual(linkedCrates(lock), ["iroh 1.4.1", "iroh-base 1.4.1", "noq 1.3.0", "noq 1.4.0"]);
  // Windows checkouts can have CRLF line endings.
  assert.deepEqual(linkedCrates(cargoLock(IROH, "\r\n")), IROH);
});

test("agrees when both name the same crates, in any order", async (t) => {
  const root = checkout(t, cargoLock(["tokio 1.53.1", ...IROH]), cargoLock([...IROH].reverse()));
  assert.deepEqual(await checkLinkLocks(root), {
    ok: true,
    crates: IROH,
    onlyApp: [],
    onlyLink: [],
    errors: [],
  });
  const result = run(root);
  assert.equal(result.status, 0, result.stderr);
  assert.match(result.stdout, /^Link lockfiles agree: iroh 1\.4\.1, iroh-base 1\.4\.1, /u);
});

test("fails on a version or a crate only one names, saying which lockfile", async (t) => {
  const app = cargoLock(["iroh 1.4.1", "iroh-base 1.4.1", "iroh-dns 1.4.1", "noq 1.3.0"]);
  const link = cargoLock(["iroh 1.4.1", "iroh-base 1.4.1", "noq 1.4.0"]);
  const root = checkout(t, app, link);
  const result = await checkLinkLocks(root);
  assert.equal(result.ok, false);
  assert.deepEqual(result.onlyApp, ["iroh-dns 1.4.1", "noq 1.3.0"]);
  assert.deepEqual(result.onlyLink, ["noq 1.4.0"]);
  const cli = run(root);
  assert.equal(cli.status, 1);
  assert.match(cli.stderr, /- only gg-app\/src-tauri\/Cargo\.lock: noq 1\.3\.0/u);
  assert.match(cli.stderr, /- only packages\/kleio-link\/Cargo\.lock: noq 1\.4\.0/u);
  assert.match(cli.stderr, /cargo update -p iroh/u);
});

test("fails when a lockfile names no iroh, even if both agree", async (t) => {
  const root = checkout(t, cargoLock(["tokio 1.53.1"]), cargoLock(["tokio 1.53.1"]));
  const result = await checkLinkLocks(root);
  assert.equal(result.ok, false);
  assert.deepEqual(result.errors, [
    "gg-app/src-tauri/Cargo.lock names no iroh",
    "packages/kleio-link/Cargo.lock names no iroh",
  ]);
  assert.equal(run(root).status, 1);
});
