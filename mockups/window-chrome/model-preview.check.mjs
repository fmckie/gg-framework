      assert.equal(await root.locator(`.thinking-choice[data-level="${label}"] span`).evaluate(e => getComputedStyle(e, '::before').visibility), 'visible');
      for (const item of await root.locator('.thinking-choice span').all()) {
        const state = await style(item);
        minimumContrast = Math.min(minimumContrast, contrast(state.color, state.fill));
        assert(contrast(state.color, state.fill) >= 4.5);
      }
      assert(contrast(selected.border, selected.fill) >= 3);
      assert(contrast('rgb(148, 162, 196)', 'rgb(67, 20, 25)') >= 3);
      const shared = await style(thinking);
      assert.equal(shared.color, selected.color);
      assert.equal(shared.fill, 'rgba(0, 0, 0, 0)');
      assert.equal(shared.weight, '700');
      assert.equal(shared.border, 'rgba(0, 0, 0, 0)');
      assert(contrast(shared.color, 'rgb(67, 20, 25)') >= 4.5);
      assert.deepEqual(await root.locator('.thinking-levels, .thinking-choice span, .status').evaluateAll(es => es.filter(e => e.scrollWidth > e.clientWidth + 1).map(e => e.className)), []);
      const slug = label.toLowerCase();
      await root.locator('.kleio-code').screenshot({ path: `mockups/window-chrome/model-thinking-${slug}-focus-${width}.png` });
      const apply = root.locator('.model-use');
      if (await apply.isEnabled()) await apply.click();
      else await root.locator('.model-cancel').click();
      await thinking.focus();
      await page.keyboard.press('Tab');
      await page.keyboard.press('Shift+Tab');
